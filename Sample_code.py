# ===================== AUDIO EXTRACTION =====================
def extract_audio(video_path, audio_path):
    """
    Extract mono 16kHz WAV audio using FFmpeg
    """
    cmd = [
        "ffmpeg", "-y",
        "-i", video_path,
        "-ac", "1",
        "-ar", "16000",
        "-vn",
        audio_path
    ]

    result = subprocess.run(
        cmd,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL
    )

    return result.returncode == 0

