# ===================== FACE ALIGNMENT FUNCTION =====================
def align_and_crop_face(image, landmarks, output_size=224):
    h, w, _ = image.shape

    # Eye landmarks
    left_eye = landmarks[33]
    right_eye = landmarks[263]

    left_eye = np.array([left_eye.x * w, left_eye.y * h])
    right_eye = np.array([right_eye.x * w, right_eye.y * h])

    # Compute rotation angle
    dy = right_eye[1] - left_eye[1]
    dx = right_eye[0] - left_eye[0]
    angle = np.degrees(np.arctan2(dy, dx))

    # Rotate image
    center = tuple(((left_eye + right_eye) / 2).astype(int))
    M = cv2.getRotationMatrix2D(center, angle, 1.0)
    rotated = cv2.warpAffine(image, M, (w, h))

    # Bounding box from landmarks
    xs = np.array([lm.x * w for lm in landmarks])
    ys = np.array([lm.y * h for lm in landmarks])

    x1, x2 = int(xs.min()), int(xs.max())
    y1, y2 = int(ys.min()), int(ys.max())

    # 🔥 ADD PADDING (prevents lip/mouth clipping)
    pad = int(0.15 * (x2 - x1))
    x1 = max(0, x1 - pad)
    y1 = max(0, y1 - pad)
    x2 = min(w, x2 + pad)
    y2 = min(h, y2 + pad)

    face = rotated[y1:y2, x1:x2]
    if face.size == 0:
        return None

    return cv2.resize(face, (output_size, output_size))

