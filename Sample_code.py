#===========================Video Standardize===================================

def standardize_video(input_video, output_video, fps=25):
    """
    Standardize FPS and codec WITHOUT resizing or clarity loss
    """
    cmd = [
        "ffmpeg", "-y",
        "-i", input_video,
        "-vsync", "cfr",
        "-r", str(fps),
        "-c:v", "libx264",
        "-preset", "slow",
        "-crf", "18",          # visually lossless
        "-pix_fmt", "yuv420p",
        output_video
    ]
    subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

#===========================Frame Extraction====================================

def extract_frames(video_path, output_dir):
    os.makedirs(output_dir, exist_ok=True)
    cap = cv2.VideoCapture(video_path)

